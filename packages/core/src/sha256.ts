/**
 * Synchronous SHA-256 (FIPS 180-4) of a string's UTF-8 bytes, as lowercase hex. Pure, no I/O.
 *
 * Used only for fingerprints of code-defined tables (the approval status mapping, review S2), where
 * the check must be synchronous and live in `packages/core`. Secrets and tokens are hashed in the
 * Worker with WebCrypto (`apps/worker/src/auth/crypto.ts`), not here.
 */
